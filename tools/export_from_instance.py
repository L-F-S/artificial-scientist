"""Export the public part of an Artificial Scientist instance into this repository.

The private instance (a research project folder) holds the single source of truth:
its CLAUDE.md operating manual and the agent skill sources.
This script copies only the publishable part into the public repository:

    CLAUDE.md, sections listed in PUBLIC_SECTIONS   ->  AS.md
    ai-team-skills/<agent>/<action>/SKILL.md         ->  skills/<agent>/<action>/SKILL.md

Sections not listed in PUBLIC_SECTIONS (instance-specific facts and house conventions)
are never exported. The convention that makes this safe is structural: anything private
goes in a non-public section of CLAUDE.md, and the public sections stay publishable.

Before anything is written, every exported file is checked:
  * against a private denylist (one term per line, '#' comments allowed), matched
    case-insensitively on word boundaries;
  * for skill frontmatter: a 'name:' field and no angle brackets in 'description:'.
If any check fails, the script lists every hit as file:line and writes nothing.

Generated paths are replaced as a whole on success; every other file in the repository
(README, docs/, example/, tools/) is left untouched.

Usage: set NETCOS_ROOT and AS_ROOT below once, then run
    python tools/export_from_instance.py
and review the result with `git diff` before committing.
"""

import re
import shutil
import sys
import tempfile
from pathlib import Path

# --- parameters (edit once) ------------------------------------------------------------
NETCOS_ROOT = Path(r"G:\Il mio Drive\Professionale\Ricerca\Assegno di ricerca - Universita di Catania\netcos")
AS_ROOT = Path(__file__).resolve().parents[1]
DENYLIST = NETCOS_ROOT / "admin" / "export_denylist.txt"

# CLAUDE.md sections that are public. "preamble" = title + "What this file is".
PUBLIC_SECTIONS = ["preamble", "1", "2", "3", "4", "5", "6", "7", "8", "10"]

GENERATED = ["AS.md", "skills"]
# ----------------------------------------------------------------------------------------

HEADER = (
    "<!-- GENERATED by tools/export_from_instance.py from the private NetCoS CLAUDE.md.\n"
    "     Do not edit here: edit the source and re-export.\n"
    "     Exported sections: {sections}. References to §9 and §11 point at the\n"
    "     instance-specific sections, which are private and intentionally not exported. -->\n\n"
    "> **Reading note.** This is the operating manual as it runs on NetCoS. Where it calls itself\n"
    "> private or backstage, that means *never part of the NetCoS product repository*. Publishing it\n"
    "> here, as a separate repository about the team, is deliberate. References to §9 and §11 point\n"
    "> to instance-specific sections that are not published.\n\n"
)


def split_sections(text):
    """Split a CLAUDE.md into {key: text}, keyed by section number or 'preamble'."""
    parts, key, buf = {}, "preamble", []
    for line in text.splitlines(keepends=True):
        m = re.match(r"^## (\d+)\.", line)
        if m:
            parts[key] = "".join(buf)
            key, buf = m.group(1), []
        elif line.startswith("## ") and key != "preamble" and not re.match(r"^## \d", line):
            parts[key] = "".join(buf)
            key, buf = "unnumbered:" + line[3:].strip(), []
        buf.append(line)
    parts[key] = "".join(buf)
    return parts


def build(stage):
    """Write the export into the empty directory `stage`."""
    claude = (NETCOS_ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    sections = split_sections(claude)
    missing = [s for s in PUBLIC_SECTIONS if s not in sections]
    if missing:
        sys.exit(f"CLAUDE.md is missing public sections: {missing}")
    body = "".join(sections[s] for s in PUBLIC_SECTIONS).rstrip() + "\n"
    body = body.rstrip("-\n ") + "\n"
    (stage / "AS.md").write_text(HEADER.format(sections=", ".join(PUBLIC_SECTIONS)) + body,
                                 encoding="utf-8", newline="\n")

    for src in sorted((NETCOS_ROOT / "ai-team-skills").glob("*/*/SKILL.md")):
        dst = stage / "skills" / src.relative_to(NETCOS_ROOT / "ai-team-skills")
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)


def check(stage):
    """Return a list of problems found in the staged export."""
    terms = []
    for line in DENYLIST.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            terms.append(line)
    pattern = re.compile(r"(?<!\w)(" + "|".join(map(re.escape, terms)) + r")(?!\w)", re.I) if terms else None

    problems = []
    for f in sorted(p for p in stage.rglob("*") if p.is_file()):
        rel = f.relative_to(stage)
        lines = f.read_text(encoding="utf-8").splitlines()
        if pattern:
            for n, line in enumerate(lines, 1):
                for m in pattern.finditer(line):
                    problems.append(f"{rel}:{n}: denylisted term '{m.group(0)}'")
        if f.name == "SKILL.md":
            head = "\n".join(lines[:10])
            if not re.search(r"^name:\s*\S", head, re.M):
                problems.append(f"{rel}: frontmatter has no name:")
            desc = re.search(r"^description:(.*)$", head, re.M)
            if desc and re.search(r"[<>]", desc.group(1)):
                problems.append(f"{rel}: description contains angle brackets (installer rejects it)")
    return problems


def main():
    if not DENYLIST.exists():
        sys.exit(f"Denylist not found: {DENYLIST} (refusing to export without it)")
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp)
        build(stage)
        problems = check(stage)
        if problems:
            print("EXPORT BLOCKED, nothing written. Fix these in the private sources:")
            print("\n".join("  " + p for p in problems))
            sys.exit(1)
        for name in GENERATED:
            target = AS_ROOT / name
            if target.is_dir():
                shutil.rmtree(target)
            elif target.exists():
                target.unlink()
            src = stage / name
            if src.is_dir():
                shutil.copytree(src, target)
            else:
                shutil.copyfile(src, target)
    n_skills = len(list((AS_ROOT / "skills").glob("*/*/SKILL.md")))
    print(f"Exported AS.md ({', '.join(PUBLIC_SECTIONS)}), {n_skills} skills -> {AS_ROOT}")
    print("Review with `git diff` before committing.")


if __name__ == "__main__":
    main()
